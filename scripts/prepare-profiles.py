#!/usr/bin/env python3
"""Register AutoSwitchCam signing IDs and obtain matching Mac App Store profiles.

Reuses the Apple Distribution identity already imported by CI. The App Store
Connect app record must first be created on Apple's website.
"""
import argparse
import base64
from datetime import datetime, timedelta, timezone
import hashlib
import importlib.util
import json
from pathlib import Path
from urllib.error import HTTPError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

spec = importlib.util.spec_from_file_location('testflight_status', Path(__file__).with_name('testflight-status.py'))
status = importlib.util.module_from_spec(spec)
spec.loader.exec_module(status)

APP_ID = 'com.diogoviannaaraujo.AutoSwitchCam'
TEAM = 'W76LFH4CZ4'


def api(key, path, query=None, data=None):
    url = 'https://api.appstoreconnect.apple.com/v1/' + path
    if query:
        url += '?' + urlencode(query)
    body = json.dumps({'data': data}).encode() if data else None
    request = Request(url, data=body, headers={
        'Authorization': 'Bearer ' + status.token(key),
        'Content-Type': 'application/json',
    })
    try:
        with urlopen(request, timeout=60) as response:
            return json.load(response)
    except HTTPError as error:
        raise RuntimeError(f'App Store Connect HTTP {error.code}: {error.read().decode()}') from error


def items(key, path, query=None):
    query = dict(query or {}, limit=200)
    while True:
        result = api(key, path, query)
        yield from result['data']
        next_url = result.get('links', {}).get('next')
        if not next_url:
            break
        # Pagination URLs are generated by Apple; only use the API path/query.
        from urllib.parse import parse_qsl, urlsplit
        parts = urlsplit(next_url)
        path = parts.path.removeprefix('/v1/')
        query = dict(parse_qsl(parts.query))


def bundle_id(key, identifier, name, capability):
    matches = list(items(key, 'bundleIds', {'filter[identifier]': identifier}))
    if not matches:
        bundle = api(key, 'bundleIds', data={
            'type': 'bundleIds',
            'attributes': {'identifier': identifier, 'name': name, 'platform': 'MAC_OS'},
        })['data']
        print('Registered ' + identifier, flush=True)
    elif len(matches) == 1:
        bundle = matches[0]
    else:
        raise ValueError('Expected exactly one bundle ID for ' + identifier)
    if bundle['attributes']['seedId'] != TEAM:
        raise ValueError('The bundle ID belongs to a different development team')
    capabilities = items(key, f"bundleIds/{bundle['id']}/bundleIdCapabilities")
    if not any(item['attributes']['capabilityType'] == capability for item in capabilities):
        api(key, 'bundleIdCapabilities', data={
            'type': 'bundleIdCapabilities',
            'attributes': {'capabilityType': capability},
            'relationships': {'bundleId': {'data': {'type': 'bundleIds', 'id': bundle['id']}}},
        })
        print(f'Enabled {capability} for {identifier}', flush=True)
    return bundle['id']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--key', type=Path, required=True)
    parser.add_argument('--identity', required=True, help='Imported signing certificate SHA-1')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True, mode=0o700)

    certificates = items(args.key, 'certificates')
    certificate = next((item for item in certificates if hashlib.sha1(
        base64.b64decode(item['attributes']['certificateContent'])
    ).hexdigest().upper() == args.identity.upper()), None)
    if not certificate:
        raise ValueError('The imported Apple Distribution certificate is not in this Apple account')

    for target, identifier, capability in (
        ('AutoSwitchCam', APP_ID, 'SYSTEM_EXTENSION_INSTALL'),
        ('AutoSwitchCamExtension', APP_ID + '.CameraExtension', 'APP_GROUPS'),
    ):
        bundle = bundle_id(args.key, identifier, target, capability)
        candidates = items(args.key, 'profiles', {
            'filter[profileType]': 'MAC_APP_STORE', 'filter[profileState]': 'ACTIVE',
            'include': 'bundleId,certificates',
        })
        profile = next((item for item in candidates if
            item['relationships']['bundleId']['data']['id'] == bundle
            and certificate['id'] in [entry['id'] for entry in item['relationships']['certificates']['data']]
            and datetime.fromisoformat(item['attributes']['expirationDate'].replace('Z', '+00:00'))
                > datetime.now(timezone.utc) + timedelta(days=1)), None)
        if not profile:
            profile = api(args.key, 'profiles', data={
                'type': 'profiles',
                'attributes': {'name': target + ' CI App Store', 'profileType': 'MAC_APP_STORE'},
                'relationships': {
                    'bundleId': {'data': {'type': 'bundleIds', 'id': bundle}},
                    'certificates': {'data': [{'type': 'certificates', 'id': certificate['id']}]},
                },
            })['data']
        destination = args.output / (target + '.provisionprofile')
        destination.write_bytes(base64.b64decode(profile['attributes']['profileContent']))
        destination.chmod(0o600)
        print(f"{target}: {profile['attributes']['name']} (expires {profile['attributes']['expirationDate']})", flush=True)

    apps = list(items(args.key, 'apps', {'filter[bundleId]': APP_ID}))
    if len(apps) != 1:
        raise RuntimeError('Create the macOS AutoSwitchCam app record at https://appstoreconnect.apple.com/apps '
                           'using bundle ID ' + APP_ID + ' before uploading to TestFlight.')
    print(f"App Store Connect: https://appstoreconnect.apple.com/apps/{apps[0]['id']}/testflight", flush=True)


if __name__ == '__main__':
    main()
